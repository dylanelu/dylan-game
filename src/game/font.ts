export function textWidth(s: string, scale = 1) { return s.length * 4 * scale - scale; }

export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, scale = 1, outline: string | null = '#07060c') {
  s = s.toUpperCase().replace(/X(?=\d)/g, 'x');
  const draw = (ox: number, oy: number, c: string) => {
    ctx.fillStyle = c;
    let cx = Math.round(x) + ox;
    for (const ch of s) {
      const rows = ROWS[ch] ?? ROWS[' '];
      for (let r = 0; r < 5; r++) for (let q = 0; q < 3; q++)
        if (rows[r][q] === '#') ctx.fillRect(cx + q * scale, Math.round(y) + oy + r * scale, scale, scale);
      cx += 4 * scale;
    }
  };
  if (outline) for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) draw(dx * scale, dy * scale, outline);
  draw(0, 0, color);
}
